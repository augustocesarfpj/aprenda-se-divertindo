-- QUESTÕES ---------------------------------------------------------------
create table if not exists public.questoes (
  id          integer generated by default as identity primary key,
  materia     text     not null,
  nivel       smallint not null check (nivel between 0 and 4),  -- 0 = fácil (questões 1 a 4)
  enunciado   text     not null,
  opcoes      jsonb    not null check (jsonb_typeof(opcoes) = 'array' and jsonb_array_length(opcoes) = 4),
  explicacao  text     not null default '',
  ativa       boolean  not null default true,
  criado_em   timestamptz not null default now()
);
comment on column public.questoes.opcoes is 'A primeira opção é sempre a correta; o jogo embaralha.';
create index if not exists questoes_materia_nivel on public.questoes (materia, nivel) where ativa;

alter table public.questoes enable row level security;
drop policy if exists "questoes ativas são públicas" on public.questoes;
create policy "questoes ativas são públicas" on public.questoes
  for select to anon, authenticated using (ativa);
grant select on public.questoes to anon, authenticated;

-- PERFIS (um por conta) --------------------------------------------------
create table if not exists public.perfis (
  id         uuid primary key references auth.users (id) on delete cascade,
  nome       text not null check (char_length(nome) between 2 and 30),
  progresso  jsonb not null default '{}'::jsonb,
  criado_em  timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

alter table public.perfis enable row level security;
drop policy if exists "ver o próprio perfil" on public.perfis;
create policy "ver o próprio perfil" on public.perfis
  for select to authenticated using ((select auth.uid()) = id);
drop policy if exists "criar o próprio perfil" on public.perfis;
create policy "criar o próprio perfil" on public.perfis
  for insert to authenticated with check ((select auth.uid()) = id);
drop policy if exists "editar o próprio perfil" on public.perfis;
create policy "editar o próprio perfil" on public.perfis
  for update to authenticated using ((select auth.uid()) = id) with check ((select auth.uid()) = id);
grant select, insert, update on public.perfis to authenticated;

-- cria o perfil automaticamente quando alguém cria a conta
create or replace function public.criar_perfil()
returns trigger language plpgsql security definer set search_path = '' as $$
declare n text := left(trim(coalesce(new.raw_user_meta_data ->> 'nome', '')), 30);
begin
  if char_length(n) < 2 then n := 'Jogador'; end if;
  insert into public.perfis (id, nome) values (new.id, n) on conflict (id) do nothing;
  return new;
end $$;
drop trigger if exists ao_criar_conta on auth.users;
create trigger ao_criar_conta after insert on auth.users
  for each row execute function public.criar_perfil();

-- PARTIDAS (base do ranking) ---------------------------------------------
create table if not exists public.partidas (
  id             bigint generated always as identity primary key,
  user_id        uuid not null default auth.uid() references auth.users (id) on delete cascade,
  modo           text not null check (modo in ('classico', 'desafio')),
  trilha         text not null check (trilha in ('geral','policial','tribunais','fiscal','administrativa')),
  questao_final  smallint not null check (questao_final between 1 and 30),
  premio         integer  not null default 0 check (premio between 0 and 1000000),
  acertos        smallint not null check (acertos between 0 and 40),
  respondidas    smallint not null check (respondidas between 0 and 40 and acertos <= respondidas),
  tempo_seg      integer check (tempo_seg >= 0),
  dia            date not null default ((now() at time zone 'America/Sao_Paulo')::date),
  criado_em      timestamptz not null default now()
);
create index if not exists partidas_user on public.partidas (user_id, criado_em desc);
-- só um desafio do dia por trilha, por pessoa
create unique index if not exists um_desafio_por_dia on public.partidas (user_id, trilha, dia) where modo = 'desafio';

alter table public.partidas enable row level security;
drop policy if exists "ver as próprias partidas" on public.partidas;
create policy "ver as próprias partidas" on public.partidas
  for select to authenticated using ((select auth.uid()) = user_id);
drop policy if exists "registrar as próprias partidas" on public.partidas;
create policy "registrar as próprias partidas" on public.partidas
  for insert to authenticated with check ((select auth.uid()) = user_id);
grant select, insert on public.partidas to authenticated;
